-- 004: run ONCE in Supabase -> SQL Editor. Makes courses editable from the website's Admin panel.
alter table public.profiles add column if not exists is_admin boolean not null default false;

create or replace function public.is_admin() returns boolean
language sql security definer stable set search_path = public as $$
  select coalesce((select is_admin from public.profiles where id = auth.uid()), false)
$$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;  -- returns false for visitors; needed by the public courses policy

alter table public.courses
  add column if not exists slug text,
  add column if not exists category text not null default 'computer',
  add column if not exists mrp int not null default 0,
  add column if not exists duration text not null default '',
  add column if not exists description text not null default '',
  add column if not exists long_description text not null default '',
  add column if not exists instructor text not null default 'GCI India Faculty',
  add column if not exists tag text not null default '',
  add column if not exists icon text not null default 'school',
  add column if not exists seo_title text not null default '',
  add column if not exists seo_desc text not null default '',
  add column if not exists learn jsonb not null default '[]'::jsonb,
  add column if not exists faq jsonb not null default '[]'::jsonb,
  add column if not exists rating numeric(2,1) not null default 0,
  add column if not exists rating_count int not null default 0,
  add column if not exists real_rating boolean not null default false,
  add column if not exists published boolean not null default true,
  add column if not exists sort_order int not null default 100;
create unique index if not exists courses_slug_key on public.courses (slug) where slug is not null;

-- new courses get their id automatically
do $$ begin
  alter table public.courses alter column id add generated by default as identity;
exception when others then null; end $$;
select setval(pg_get_serial_sequence('public.courses', 'id'), greatest((select coalesce(max(id), 0) from public.courses), 1));

-- visitors see only published courses; admins see everything and can edit
drop policy if exists "courses readable" on public.courses;
drop policy if exists "published courses readable" on public.courses;
create policy "published courses readable" on public.courses for select to anon, authenticated using (published or public.is_admin());
drop policy if exists "admin manage courses" on public.courses;
create policy "admin manage courses" on public.courses for all to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "admin manage lessons" on public.lessons;
create policy "admin manage lessons" on public.lessons for all to authenticated using (public.is_admin()) with check (public.is_admin());
grant insert, update, delete on public.courses, public.lessons to authenticated;

-- public bucket for course thumbnails (only admins can upload)
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('thumbnails', 'thumbnails', true, 2097152, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update set public = true, file_size_limit = 2097152, allowed_mime_types = array['image/jpeg', 'image/png', 'image/webp'];
drop policy if exists "admin upload thumbnails" on storage.objects;
create policy "admin upload thumbnails" on storage.objects for insert to authenticated with check (bucket_id = 'thumbnails' and public.is_admin());
drop policy if exists "admin update thumbnails" on storage.objects;
create policy "admin update thumbnails" on storage.objects for update to authenticated using (bucket_id = 'thumbnails' and public.is_admin());
drop policy if exists "admin delete thumbnails" on storage.objects;
create policy "admin delete thumbnails" on storage.objects for delete to authenticated using (bucket_id = 'thumbnails' and public.is_admin());

